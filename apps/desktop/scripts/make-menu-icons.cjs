// Renders the icons of the application menu (File, Edit, View, Window, Help) from lucide, the icon set the
// app uses everywhere else, into small PNGs embedded in electron/menu-icons.generated.ts.
// Native menus can't draw SVG, so each icon is drawn at 16 px and 32 px (for 2× screens) in two inks:
// dark (light menus, and macOS template images) and light (dark menus on Windows / Linux).
//
// Run: npm run menu-icons -w @testpion/desktop   (re-run after changing ICONS)
const { app, BrowserWindow } = require('electron');
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { createElement } = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const lucide = require('lucide-react');

/** Menu icon name → lucide component name. */
const ICONS = {
  newTab: 'SquarePlus',
  new: 'FilePlus2',
  http: 'Network',
  graphql: 'GitBranch',
  grpc: 'Waypoints',
  websocket: 'Radio',
  mcp: 'Plug',
  collection: 'FolderPlus',
  environment: 'KeyRound',
  monitor: 'AlarmClock',
  workspace: 'Layers',
  openFolder: 'FolderOpen',
  import: 'Upload',
  export: 'Download',
  exportCollection: 'FolderTree',
  save: 'Save',
  closeTab: 'X',
  closeOthers: 'ListX',
  closeAll: 'CopyX',
  settings: 'Settings',
  quit: 'LogOut',
  undo: 'Undo2',
  redo: 'Redo2',
  cut: 'Scissors',
  copy: 'Copy',
  paste: 'ClipboardPaste',
  delete: 'Trash2',
  selectAll: 'TextSelect',
  reload: 'RotateCw',
  devtools: 'SquareTerminal',
  resetZoom: 'SearchCheck',
  zoomIn: 'ZoomIn',
  zoomOut: 'ZoomOut',
  fullscreen: 'Maximize2',
  minimize: 'Minus',
  maximize: 'Square',
  closeWindow: 'AppWindow',
  updates: 'RefreshCw',
  examples: 'Sparkles',
  docs: 'BookOpen',
  releaseNotes: 'ScrollText',
  issue: 'Bug',
};

const INKS = { dark: '#1f2937', light: '#e5e7eb' };

const svgFor = (name, color) => {
  const Icon = lucide[name];
  if (!Icon) throw new Error(`lucide-react has no icon ${name}`);
  return renderToStaticMarkup(createElement(Icon, { size: 24, color, strokeWidth: 2, absoluteStrokeWidth: false }));
};

app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false });
  await win.loadURL('data:text/html,<html></html>');
  const render = (svg, px) =>
    win.webContents.executeJavaScript(
      `new Promise((ok, fail) => {
        const img = new Image();
        img.onload = () => {
          const c = document.createElement('canvas');
          c.width = c.height = ${px};
          c.getContext('2d').drawImage(img, 0, 0, ${px}, ${px});
          ok(c.toDataURL('image/png'));
        };
        img.onerror = () => fail(new Error('render failed'));
        img.src = ${JSON.stringify('data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64'))};
      })`,
    );
  const out = {};
  for (const [key, name] of Object.entries(ICONS)) {
    out[key] = {};
    for (const [ink, color] of Object.entries(INKS)) {
      const svg = svgFor(name, color);
      out[key][ink] = [await render(svg, 16), await render(svg, 32)];
    }
  }
  const file = join(__dirname, '..', 'electron', 'menu-icons.generated.ts');
  writeFileSync(
    file,
    `// Generated by scripts/make-menu-icons.cjs from lucide icons (ISC license). Do not edit.\n` +
      `/** PNG data URLs [1×, 2×] per icon, in a dark ink (light menus, macOS templates) and a light ink (dark menus). */\n` +
      `export const MENU_ICONS: Record<string, { dark: [string, string]; light: [string, string] }> = ${JSON.stringify(out, null, 1)};\n`,
  );
  console.log(`[menu-icons] ${Object.keys(out).length} icons written to ${file}`);
  app.quit();
});
